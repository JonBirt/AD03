
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import org.vibur.dbcp.ViburDBCPDataSource;

public class PruebaVibur {

    public static void main(String[] args) {

        ViburDBCPDataSource pool = new ViburDBCPDataSource();

        pool.setJdbcUrl("jdbc:hsqldb:file:basedatos");
        pool.setUsername("SA");
        pool.setPassword("");

        pool.setPoolInitialSize(1);
        pool.setPoolMaxSize(5);

        try {
            // Iniciar el pool.
            pool.start();

            // Obtener y cerrar la conexión automáticamente.
            try (Connection conexion = pool.getConnection()) {

                boolean valida = conexion.isValid(2);
                System.out.println("Conexión válida: " + valida);

                if (valida) {

                    // Crear la tabla si no existe.
                    String crearTabla =
                        "CREATE TABLE IF NOT EXISTS comprobacion (" +
                        "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                        "mensaje VARCHAR(100))";

                    try (Statement sentencia = conexion.createStatement()) {

                        sentencia.executeUpdate(crearTabla);

                        // Insertar una fila.
                        sentencia.executeUpdate(
                            "INSERT INTO comprobacion (mensaje) " +
                            "VALUES ('Conexión HSQLDB mediante Vibur correcta')"
                        );

                        // Consultar la tabla.
                        String consulta =
                            "SELECT id, mensaje FROM comprobacion";

                        try (ResultSet resultado =
                                sentencia.executeQuery(consulta)) {

                            while (resultado.next()) {
                                System.out.println(
                                    resultado.getInt("id") + " - " +
                                    resultado.getString("mensaje")
                                );
                            }
                        }
                    }
                }
            }

        } catch (SQLException e) {
            System.out.println("Error al trabajar con HSQLDB:");
            e.printStackTrace();

        } finally {
            // Finalizar el pool.
            pool.terminate();
        }
    }
}
